#!/usr/bin/env python3
"""accessors.go, the accessor of go-pfcp that reads the value of each IE type that it has:
the method of *ie.IE named as the constant of the type, without arguments, whose last
result is an error. A type without such a method is one whose value it does not read.

    python3 tests/go-pfcp/accessors.py GO_PFCP_DIR | gofmt > tests/go-pfcp/accessors.go

GO_PFCP_DIR is go-pfcp at the version that go.mod names, as
`go mod download -json github.com/wmnsk/go-pfcp@v0.0.24` gives its "Dir".
"""
import os
import re
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
root = sys.argv[1]
constants = open(os.path.join(root, 'ie', 'ie.go'), encoding='utf-8').read()
block = constants[constants.index('const ('):]
block = block[:block.index('\n)')]
types = re.findall(r'^\s*([A-Z]\w*)\s+uint16\s*=\s*(\d+)', block, re.M)
methods = {}
for name in os.listdir(os.path.join(root, 'ie')):
    if name.endswith('.go') and not name.endswith('_test.go'):
        text = open(os.path.join(root, 'ie', name), encoding='utf-8').read()
        for method, results in re.findall(r'^func \(i \*IE\) ([A-Z]\w*)\(\) \(([^)]*error)\)', text, re.M):
            methods[method] = results.count(',')
print('// Code generated by accessors.py from go-pfcp v0.0.24; DO NOT EDIT.')
print()
print('package main')
print()
print('import "github.com/wmnsk/go-pfcp/ie"')
print()
print('// The accessor of the value of each IE type that go-pfcp reads, by its type.')
print('var accessors = map[uint16]func(*ie.IE) error{')
for name, number in types:
    if name in methods:
        ignored = '_, ' * methods[name]
        print(f'\tie.{name}: func(i *ie.IE) error {{ {ignored}err := i.{name}(); return err }},')
print('}')
